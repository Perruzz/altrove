WIDTH, HEIGHT = 360, 180  # one cell per degree
SCALE = 8  # rasterise at 8 px per degree, then average down
LAND_THRESHOLD = 0.38  # a cell is land when at least this share of it is covered


def rasterize() -> np.ndarray:
    """Returns a HEIGHT x WIDTH boolean grid; row 0 is the northernmost degree."""
    image = Image.new("L", (WIDTH * SCALE, HEIGHT * SCALE), 0)
    draw = ImageDraw.Draw(image)

    def paint(points, value):
        # Drawn three times, a full turn apart, so shapes crossing the antimeridian wrap.
        for shift in (-360, 0, 360):
            draw.polygon(
                [((lng + shift + 180) * SCALE, (90 - lat) * SCALE) for lng, lat in points],
                fill=value,
            )

    for points in LAND.values():
        paint(points, 255)
    for points in WATER.values():
        paint(points, 0)

    cells = np.asarray(image, dtype=np.float32) / 255.0
    cells = cells.reshape(HEIGHT, SCALE, WIDTH, SCALE).mean(axis=(1, 3))
    return cells >= LAND_THRESHOLD


def write_kotlin(mask: np.ndarray) -> None:
    packed = np.packbits(mask.astype(np.uint8), axis=None, bitorder="big").tobytes()
    encoded = base64.b64encode(packed).decode("ascii")
    lines = [encoded[i : i + 100] for i in range(0, len(encoded), 100)]
    body = " +\n".join(f'        "{line}"' for line in lines)
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(
        "package app.altrove.ui.space\n"
        "\n"
        "// Generated by tools/earth_mask.py. Do not edit by hand.\n"
        "//\n"
        f"// A {WIDTH} x {HEIGHT} grid, one bit per degree of longitude and latitude, row by row from the\n"
        "// North Pole and from 180 degrees west; a set bit means land. Bits are packed most\n"
        "// significant first and the bytes are Base64-encoded.\n"
        f"internal const val EARTH_MASK_WIDTH = {WIDTH}\n"
        f"internal const val EARTH_MASK_HEIGHT = {HEIGHT}\n"
        "\n"
        "internal const val EARTH_MASK_BASE64: String =\n"
        f"{body}\n"
    )
    print(f"wrote {OUTPUT} ({len(packed)} bytes, {mask.mean() * 100:.1f}% land)")


def preview(mask: np.ndarray, directory: pathlib.Path) -> None:
    """Writes a flat map and a few globe views, drawn the way the app draws them."""
    directory.mkdir(parents=True, exist_ok=True)
    flat = Image.fromarray(np.where(mask, 235, 20).astype(np.uint8))
    flat.resize((WIDTH * 4, HEIGHT * 4), Image.NEAREST).save(directory / "flat.png")

    count = 9000
    index = np.arange(count) + 0.5
    y = 1 - 2 * index / count
    radius = np.sqrt(1 - y * y)
    theta = index * math.pi * (3 - math.sqrt(5))
    x, z = np.cos(theta) * radius, np.sin(theta) * radius
    lat, lng = np.degrees(np.arcsin(y)), np.degrees(np.arctan2(x, z))
    rows = np.clip((90 - lat).astype(int), 0, HEIGHT - 1)
    cols = np.clip((lng + 180).astype(int), 0, WIDTH - 1)
    land = mask[rows, cols]

    views = {"europe_africa": (25, 15), "americas": (15, -85), "asia": (25, 105), "pacific": (-15, 150)}
    size, r = 520, 240
    for name, (lat0, lng0) in views.items():
        a, b = math.radians(lng0), math.radians(lat0)
        x1 = x * math.cos(a) - z * math.sin(a)
        z1 = x * math.sin(a) + z * math.cos(a)
        y2 = y * math.cos(b) - z1 * math.sin(b)
        z2 = y * math.sin(b) + z1 * math.cos(b)
        image = Image.new("RGB", (size, size), (6, 6, 26))
        draw = ImageDraw.Draw(image)
        draw.ellipse([size / 2 - r, size / 2 - r, size / 2 + r, size / 2 + r], fill=(14, 14, 48))
        for i in np.nonzero(land & (z2 > 0))[0]:
            px, py = size / 2 + r * x1[i], size / 2 - r * y2[i]
            shade = int(90 + 165 * z2[i])
            draw.ellipse([px - 1.6, py - 1.6, px + 1.6, py + 1.6], fill=(shade, shade, 255))
        image.save(directory / f"globe_{name}.png")
    print(f"previews in {directory}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--preview", type=pathlib.Path, help="directory for preview images")
    args = parser.parse_args()
    mask = rasterize()
    write_kotlin(mask)
    if args.preview:
        preview(mask, args.preview)


if __name__ == "__main__":
    main()
